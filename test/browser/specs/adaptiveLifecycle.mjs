/** Native lifecycle controls use a local fake RPC only; external requests are blocked. */
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { launchBrowser, blockExternalRequests } from '../../support/browser/runtime.mjs';
const output = '/tmp/cv-adaptive-lifecycle-browser';
await mkdir(output, { recursive: true });
const browser = await launchBrowser();
try {
  for (const width of [1440, 390]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 } });
    const external = [], errors = []; await blockExternalRequests(context, external);
    const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:5177/cv-harness/test/browser/pages/adaptive-search.html', { waitUntil: 'networkidle' });
    await page.locator('.search-adaptive > summary > span:not(.info-hint)').click();
    await page.locator('.lifecycle > summary').click();
    assert.equal(await page.evaluate(() => window.adaptiveFixture.snapshot().calls.filter(call => /lifecycle/u.test(call.name)).length), 0);
    await page.getByRole('button', { name: 'Abort and reserve restart', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm abort and reserve restart', exact: true }).waitFor();
    const prepared = await page.evaluate(() => window.adaptiveFixture.snapshot().calls.filter(call => /lifecycle/u.test(call.name)));
    assert.deepEqual(prepared.map(call => call.name), ['prepare_adaptive_search_lifecycle']);
    const operation = prepared[0].args.p_operation_id;
    await page.getByRole('button', { name: 'Copy exact instructions', exact: true }).click();
    await page.waitForFunction(() => window.adaptiveFixture.snapshot().copied.includes('LIFECYCLE CONTRACT 1'));
    const copied = await page.evaluate(() => window.adaptiveFixture.snapshot().copied);
    assert(copied.includes(operation)); assert(copied.includes('reserved_not_dispatched')); assert(!copied.includes('begin_adaptive_opportunity_search('));
    await page.getByRole('button', { name: 'Confirm abort and reserve restart', exact: true }).click();
    await page.locator('.lifecycle-record').getByText('Verified', { exact: true }).waitFor();
    const calls = await page.evaluate(() => window.adaptiveFixture.snapshot().calls.filter(call => /lifecycle/u.test(call.name)));
    assert.deepEqual(calls.map(call => call.name), ['prepare_adaptive_search_lifecycle', 'apply_adaptive_search_lifecycle', 'read_adaptive_search_lifecycle']);
    assert(calls.every(call => call.args.p_operation_id === operation));
    assert.equal(await page.getByRole('button', { name: 'Confirm abort and reserve restart', exact: true }).count(), 0);
    await page.screenshot({ path: `${output}/verified-${width}.png`, fullPage: true });
    const overflow = await page.locator('.lifecycle').evaluate(element => element.scrollWidth > element.clientWidth);
    assert.equal(overflow, false); assert.deepEqual(external, []); assert.deepEqual(errors, []);
    await page.reload({ waitUntil: 'networkidle' });
    await page.locator('.search-adaptive > summary > span:not(.info-hint)').click();
    await page.locator('.lifecycle > summary').click();
    assert.equal(await page.getByRole('button', { name: 'Check saved operation', exact: true }).isEnabled(), true);
    assert.equal(await page.getByRole('button', { name: 'Abort current execution', exact: true }).isDisabled(), true);
    assert.equal(await page.evaluate(() => window.adaptiveFixture.snapshot().calls.filter(call => /lifecycle/u.test(call.name)).length), 0, 'restoration must not replay a lifecycle request');
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem(Object.keys(localStorage).find(key => key.startsWith('CV_ADAPTIVE_LIFECYCLE:')))).operation_id), operation);
    await context.close();
  }
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const external = []; await blockExternalRequests(context, external);
  const page = await context.newPage();
  await page.goto('http://127.0.0.1:5177/cv-harness/test/browser/pages/adaptive-search.html', { waitUntil: 'networkidle' });
  await page.locator('.search-adaptive > summary > span:not(.info-hint)').click();
  await page.locator('.lifecycle > summary').click();
  await page.getByRole('button', { name: 'Abort current execution', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm abort', exact: true }).waitFor();
  await page.evaluate(() => window.adaptiveFixture.denyLifecycle());
  await page.getByRole('button', { name: 'Confirm abort', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.lifecycle')?.getAttribute('aria-busy') === 'false');
  assert.equal(await page.getByRole('button', { name: 'Check saved operation', exact: true }).isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: 'Abort current execution', exact: true }).isDisabled(), true);
  assert.equal(await page.evaluate(() => window.adaptiveFixture.snapshot().calls.filter(call => call.name === 'read_adaptive_search_lifecycle').length), 0, 'denial must stop before verification');
  assert.deepEqual(external, []); await context.close();
  const noActiveContext = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const noActiveExternal = []; await blockExternalRequests(noActiveContext, noActiveExternal);
  const noActivePage = await noActiveContext.newPage();
  await noActivePage.goto('http://127.0.0.1:5177/cv-harness/test/browser/pages/adaptive-search.html', { waitUntil: 'networkidle' });
  await noActivePage.locator('.search-adaptive > summary > span:not(.info-hint)').click();
  await noActivePage.locator('.lifecycle > summary').click();
  await noActivePage.evaluate(() => window.adaptiveFixture.noActiveLifecycle());
  await noActivePage.getByRole('button', { name: 'Abort and reserve restart', exact: true }).click();
  await noActivePage.locator('.lifecycle-record').getByText('No active execution', { exact: true }).waitFor();
  assert.equal(await noActivePage.getByRole('button', { name: 'Confirm abort and reserve restart', exact: true }).count(), 0);
  assert.deepEqual(await noActivePage.evaluate(() => window.adaptiveFixture.snapshot().calls.filter(call => /lifecycle/u.test(call.name)).map(call => call.name)), ['prepare_adaptive_search_lifecycle']);
  assert.deepEqual(noActiveExternal, []); await noActiveContext.close();
  console.log('PASS native lifecycle controls: prepare/confirm/read, pinned IDs, reserved-only restart, bounded copy, denied/no-active stops, reload without replay, desktop/mobile.');
} finally { await browser.close(); }
