import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
export const DATABASE_SCHEMA_PATH = 'supabase/schema.sql';
export const DATABASE_MODULE_MANIFEST = 'supabase/schemas/manifest.json';

export function databaseSchemaFiles(): string[] {
  const manifest = JSON.parse(readFileSync(resolve(root, DATABASE_MODULE_MANIFEST), 'utf8'));
  if (manifest.version !== 1 || !Array.isArray(manifest.files) || !manifest.files.length
    || manifest.files.some((name: unknown) => typeof name !== 'string' || !/^\d{2}_[a-z_]+\.sql$/u.test(name))
    || new Set(manifest.files).size !== manifest.files.length) {
    throw new Error('The database module manifest must contain unique, ordered SQL filenames.');
  }
  return manifest.files.map((name: string) => `supabase/schemas/${name}`);
}

export function buildDatabaseSchema(): string {
  const modules = databaseSchemaFiles().map(path => {
    const sql = readFileSync(resolve(root, path), 'utf8').trim();
    if (!sql) throw new Error(`Empty database schema module: ${path}`);
    return `-- ${path}\n${sql}`;
  });
  return '-- Generated by scripts/databaseSchema.ts from supabase/schemas/manifest.json.\n'
    + '-- Edit the owning schema module, then run npm run db:schema:write.\n'
    + '-- Current schema only; install into an empty database with Supabase Auth available.\n\n'
    + 'begin;\nset local check_function_bodies = false;\n\n'
    + modules.join('\n\n') + '\n\ncommit;\n';
}

export function checkDatabaseSchema(): void {
  if (readFileSync(resolve(root, DATABASE_SCHEMA_PATH), 'utf8') !== buildDatabaseSchema()) {
    throw new Error('Database schema is stale. Run npm run db:schema:write.');
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length > 1 || args.length === 1 && !['--check', '--write'].includes(args[0]!)) {
    throw new Error('Use --check or --write. This command only reads and writes local SQL files.');
  }
  if (args[0] === '--write') {
    writeFileSync(resolve(root, DATABASE_SCHEMA_PATH), buildDatabaseSchema());
    process.stdout.write('Generated the current atomic database schema.\n');
  } else {
    checkDatabaseSchema();
    process.stdout.write('Database schema matches its ordered source modules.\n');
  }
}
